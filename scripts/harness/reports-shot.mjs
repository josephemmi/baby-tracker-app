import { chromium, freshDb, seedSleeps, setClock, newPhone, HIDE_DEV_UI, hits } from "./lib.mjs";
import { mock, asOf, T_DEFAULT } from "./mock.mjs";
const SP = (process.env.HARNESS_OUT ?? "/tmp/harness-out");
const width = +(process.argv[2] ?? 393);
const out = process.argv[3] ?? `${SP}/shots/reports-${width}.png`;
const T = T_DEFAULT;
const db = "t_reports";
freshDb(db);
seedSleeps(db, asOf(mock(), T));
setClock(db, new Date(T).toISOString());
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const { page } = await newPhone(browser, { db, user: "joseph", width, time: T });
await page.goto(`http://localhost:3100/dev-preview/sleep-reports?w=${width}`);
await page.addStyleTag({ content: HIDE_DEV_UI });
await page.getByText("Naps today").waitFor({ timeout: 30000 });
await page.waitForTimeout(500);
await page.screenshot({ path: out, fullPage: true });
console.log("saved", out, "requests:", hits.filter((h) => h.kind !== "unhandled").length, "unhandled:", JSON.stringify(hits.filter((h) => h.kind === "unhandled" || h.kind === "error").slice(0, 5)));
await browser.close();
